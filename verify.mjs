import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';

const browser = await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:960},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
try {
  await page.goto('http://127.0.0.1:5173',{waitUntil:'networkidle'});
  await page.locator('.loading-screen').waitFor({state:'detached',timeout:90000});
  await page.locator('canvas').waitFor();
  await page.waitForTimeout(3500);
  if(await page.locator('.scene-wrap > .error-panel').count())throw new Error(`3D fallback visible: ${errors.join('\n')}`);
  await mkdir('artifacts',{recursive:true});
  await page.screenshot({path:'artifacts/gallery-desktop.png'});
  const canvasVisible=await page.locator('canvas').evaluate(canvas=>{const gl=canvas.getContext('webgl2');if(!gl)return false;const bytes=new Uint8Array(4);gl.readPixels(Math.floor(canvas.width*.5),Math.floor(canvas.height*.5),1,1,gl.RGBA,gl.UNSIGNED_BYTE,bytes);return [...bytes].slice(0,3).some(c=>c>45);});
  if(!canvasVisible)throw new Error('Canvas center has no rendered artwork');
  await page.mouse.move(700,450);await page.mouse.down();await page.mouse.move(850,500,{steps:12});await page.mouse.up();
  await page.waitForTimeout(800);
  const rotated=await page.locator('canvas').getAttribute('data-rotation');
  if(Math.abs(Number(rotated.split(',')[1]))<.5)throw new Error('Drag rotation failed');
  await page.mouse.move(650,400);await page.mouse.down();await page.mouse.move(1000,650,{steps:15});await page.mouse.up();
  await page.waitForTimeout(800);
  await page.screenshot({path:'artifacts/gallery-extreme-angle.png'});
  await page.mouse.wheel(0,-250);await page.waitForTimeout(800);
  if(Number(await page.locator('canvas').getAttribute('data-zoom'))>7)throw new Error('Wheel zoom failed');
  await page.getByRole('button',{name:'重置视角'}).click();await page.waitForTimeout(800);
  if(Math.abs(Number(await page.locator('canvas').getAttribute('data-zoom'))-7.65)>.1)throw new Error('Zoom reset failed');
  await page.getByRole('button',{name:'选择边框样式'}).click();
  await page.getByRole('button',{name:'曜石黑',exact:true}).click();
  if(!(await page.getByRole('button',{name:'选择边框样式'}).textContent()).includes('曜石黑'))throw new Error('Material selection failed');
  await page.getByRole('button',{name:'展示无声潮汐'}).click();
  if(await page.getByRole('button',{name:'展示无声潮汐'}).getAttribute('aria-pressed')!=='true')throw new Error('Artwork selection failed');
  await page.getByRole('button',{name:'切换冷色光照'}).click();
  await page.getByRole('button',{name:'切换暖色光照'}).waitFor();
  await page.getByRole('button',{name:'进入沉浸模式'}).click();
  await page.locator('.app.focus-mode').waitFor();
  await page.keyboard.press('Escape');
  if(await page.locator('.app.focus-mode').count())throw new Error('Focus escape failed');
  await page.getByRole('button',{name:'使用说明'}).click();
  await page.getByRole('dialog').waitFor();
  await page.keyboard.press('Escape');
  const poster=await page.locator('.poster-thumb img').first().getAttribute('src');
  await page.locator('input[type=file]').setInputFiles({name:'my-poster.png',mimeType:'image/png',buffer:Buffer.from(poster.split(',')[1],'base64')});
  await page.getByRole('status').filter({hasText:'你的海报已置入展框'}).waitFor();
  await page.waitForTimeout(1000);
  const downloadEvent=page.waitForEvent('download');
  await page.getByRole('button',{name:'导出展厅图片'}).click();
  const download=await downloadEvent;
  if(!download.suggestedFilename().endsWith('.png'))throw new Error('Export failed');
  await download.saveAs('artifacts/exported-scene.png');
  await page.locator('input[type=file]').setInputFiles({name:'invalid.txt',mimeType:'text/plain',buffer:Buffer.from('invalid')});
  await page.getByRole('status').filter({hasText:'请选择 JPG'}).waitFor();
  await page.waitForTimeout(4000);
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(1500);
  await page.screenshot({path:'artifacts/gallery-mobile.png',fullPage:true});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  if(overflow)throw new Error('Mobile horizontal overflow');
  if(errors.length)throw new Error(errors.join('\n'));
  await writeFile('artifacts/verification.json',JSON.stringify({passed:true,checks:['WebGL renders artwork','drag rotation','wheel zoom','reset rotation and zoom','material selection','artwork switching','lighting toggle','focus and Escape','help dialog','local image upload','invalid file rejection','PNG export','mobile layout without overflow'],consoleErrors:errors},null,2));
  console.log('PASS: 13 browser checks; desktop/mobile screenshots and PNG export saved to artifacts/.');
} finally {await browser.close();}
